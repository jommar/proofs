import http from 'node:http';
import net from 'node:net';
import { loopbackAddress, targetMode } from '../lib/origins.mjs';

export const proxyFailureHeader = 'x-proof-proxy-failure';

// Local runs resolve to loopback directly; target runs (--url) let the proxy resolve the named host.
const upstreamHost = hostname => loopbackAddress(hostname) ?? (targetMode() ? hostname : undefined);

// Playwright routes see only the first URL in a redirect chain. Restrict HTTP
// requests and HTTPS CONNECT at the browser's transport boundary instead.
export async function loopbackProxy(allowed) {
  const accept = (url, protocol) => url.protocol === protocol && !url.username && !url.password && allowed.has(url.origin);
  const server = http.createServer((req, res) => {
    let url;
    try { url = new URL(req.url); } catch { /* malformed proxy target */ }
    if (!url || !accept(url, 'http:')) return res.writeHead(403).end();
    const { ['proxy-authorization']: _auth, ['proxy-connection']: _connection, ...headers } = req.headers;
    const upstream = http.request({
      host: upstreamHost(url.hostname), port: url.port || 80, method: req.method,
      path: url.pathname + url.search, headers,
    }, response => {
      // Only a failure generated by this HTTP proxy may carry the marker.
      const { [proxyFailureHeader]: _marker, ...forwarded } = response.headers;
      res.writeHead(response.statusCode, forwarded);
      response.pipe(res);
      response.on('error', () => res.destroy());
    });
    upstream.on('error', () => {
      if (res.headersSent) res.destroy();
      else res.writeHead(502, { [proxyFailureHeader]: '1', 'content-type': 'text/plain' }).end('Local service unavailable');
    });
    res.on('close', () => upstream.destroy());
    req.pipe(upstream);
  });
  server.on('connect', (req, downstream, head) => {
    let url;
    try { url = new URL(`https://${req.url}`); } catch { /* malformed tunnel target */ }
    if (!url || !accept(url, 'https:')) return downstream.end('HTTP/1.1 403 Forbidden\r\n\r\n');
    const upstream = net.connect(Number(url.port || 443), upstreamHost(url.hostname));
    upstream.once('connect', () => {
      downstream.write('HTTP/1.1 200 Connection Established\r\n\r\n');
      if (head.length) upstream.write(head);
      upstream.pipe(downstream).pipe(upstream);
    });
    upstream.on('error', () => downstream.destroy());
    downstream.on('error', () => upstream.destroy());
    downstream.on('close', () => upstream.destroy());
  });
  const clients = new Set();
  server.on('connection', socket => {
    clients.add(socket);
    socket.once('close', () => clients.delete(socket));
  });
  await new Promise((resolve, reject) => {
    server.once('error', reject);
    server.listen(0, '127.0.0.1', resolve);
  });
  return {
    url: `http://127.0.0.1:${server.address().port}`,
    close() {
      for (const socket of clients) socket.destroy();
      server.close();
    },
  };
}
